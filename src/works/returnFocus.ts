// 작품 페이지에서 나온 방문자의 초점이 어느 작품으로 가야 하는가
// (Requirements 40·41). 한 건짜리 넘김 상자다 — 나오는 쪽이 넣고, 도착한
// 화면(홈 셸)이 꺼내 쓴다.
//
// 여기 담기는 것은 "들어온 자리"가 아니라 **주소에 적혀 있던 작품** 하나다.
// 어디로 갈지는 아무도 기억하지 않는다: 되감기면 들어온 자리가 그대로 다시
// 뜨고, 되감을 자리가 없으면 씬을 띄울 수 있는지가 목적지를 정한다 (B4의
// 판정 한 곳). 그래서 방울로 들어왔는데 그새 씬을 쓸 수 없게 되어도 도착한
// 화면에서 이 slug의 항목이 다시 찾아지고, 기억이 어긋날 자리가 없다.
//
// **모듈 변수인 것이 이 상자의 계약이다.** 페이지가 다시 로드되면 모듈도
// 새로 실행되므로 상자는 반드시 비어 있다 — 새로고침한 방문자에게는 들어온
// 자리가 없다는 Requirement 41이 저장소가 아니라 이 사실 위에 선다. 세션
// 저장소나 히스토리 state처럼 페이지 수명을 넘겨 살아남는 자리에 두면 그
// 요구가 조용히 깨진다.

let pending: string | null = null

/** 나오는 길에 걸어 둔다 — 도착한 화면에서 이 작품에 초점을 둔다. */
export function requestWorkFocus(slug: string): void {
  pending = slug
}

/**
 * 걸린 것을 꺼낸다. 한 번 꺼내면 비므로 같은 요청이 나중 화면에 두 번
 * 적용되지 않는다. 걸린 것이 없으면 null — 방문자에게서 초점을 빼앗지
 * 않는다 (마우스로 홈 링크를 눌러 나온 방문자가 그렇다).
 */
export function takeWorkFocus(): string | null {
  const slug = pending
  pending = null
  return slug
}
